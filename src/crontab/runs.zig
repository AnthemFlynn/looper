test "metaWrite then metaRead round-trips through the filesystem" {
    var arena = std.heap.ArenaAllocator.init(testing.allocator);
    defer arena.deinit();
    const a = arena.allocator();
    const run_id = try std.fmt.allocPrint(a, "test-rw-{x}", .{posix.nowEpoch()});
    const original = RunRecord{
        .run_id = run_id,
        .command = "/bin/echo round-trip",
        .once = true,
        .scheduled_for = 1748016000,
        .started_at = 1748016001,
        .finished_at = 1748016002,
        .exit_code = 0,
    };
    try metaWrite(a, original);
    defer {
        // Cleanup: remove the run dir we created.
        removeRunDir(a, run_id);
    }
    const got = (try metaRead(a, run_id)).?;
    try testing.expectEqualStrings(original.run_id, got.run_id);
    try testing.expectEqualStrings(original.command, got.command);
    try testing.expectEqual(original.once, got.once);
    try testing.expectEqual(original.scheduled_for, got.scheduled_for);
    try testing.expectEqual(original.exit_code, got.exit_code);
}
