const testing = std.testing;

test "statusOf classifies all four lifecycle states" {
    try testing.expectEqual(RunStatus.pending, statusOf(.{ .run_id = "x", .command = "c" }));
    try testing.expectEqual(RunStatus.running, statusOf(.{ .run_id = "x", .command = "c", .started_at = 100 }));
    try testing.expectEqual(RunStatus.done, statusOf(.{ .run_id = "x", .command = "c", .started_at = 100, .finished_at = 200, .exit_code = 0 }));
    try testing.expectEqual(RunStatus.failed, statusOf(.{ .run_id = "x", .command = "c", .started_at = 100, .finished_at = 200, .exit_code = 1 }));
    try testing.expectEqual(RunStatus.failed, statusOf(.{ .run_id = "x", .command = "c", .started_at = 100, .finished_at = 200, .timed_out = true }));
}

test "metaSerialize emits canonical key=value lines" {
    var arena = std.heap.ArenaAllocator.init(testing.allocator);
    defer arena.deinit();
    const a = arena.allocator();
    const r = RunRecord{
        .run_id = "abc123",
        .source_id = "daily-backup",
        .command = "/bin/echo hi",
        .target_label = "local",
        .once = true,
        .scheduled_for = 1748016000,
        .started_at = 1748016001,
        .finished_at = 1748016003,
        .exit_code = 0,
    };
    const bytes = try metaSerialize(a, r);
    try testing.expect(std.mem.indexOf(u8, bytes, "run_id=abc123\n") != null);
    try testing.expect(std.mem.indexOf(u8, bytes, "source_id=daily-backup\n") != null);
    try testing.expect(std.mem.indexOf(u8, bytes, "command=/bin/echo hi\n") != null);
    try testing.expect(std.mem.indexOf(u8, bytes, "once=1\n") != null);
    try testing.expect(std.mem.indexOf(u8, bytes, "exit_code=0\n") != null);
    try testing.expect(std.mem.indexOf(u8, bytes, "timed_out=0\n") != null);
}

test "metaSerialize + metaParse round-trip" {
    var arena = std.heap.ArenaAllocator.init(testing.allocator);
    defer arena.deinit();
    const a = arena.allocator();
    const original = RunRecord{
        .run_id = "round-trip-test",
        .source_id = "src-1",
        .command = "/usr/bin/env DEMO=x /bin/echo hi",
        .target_label = "file:/tmp/x.crontab",
        .once = true,
        .scheduled_for = 1748016000,
        .started_at = 1748016001,
        .finished_at = 1748016003,
        .exit_code = 0,
        .timed_out = false,
    };
    const bytes = try metaSerialize(a, original);
    const parsed = try metaParse(a, bytes);
    try testing.expectEqualStrings(original.run_id, parsed.run_id);
    try testing.expectEqualStrings(original.source_id.?, parsed.source_id.?);
    try testing.expectEqualStrings(original.command, parsed.command);
    try testing.expectEqualStrings(original.target_label.?, parsed.target_label.?);
    try testing.expectEqual(original.once, parsed.once);
    try testing.expectEqual(original.scheduled_for.?, parsed.scheduled_for.?);
    try testing.expectEqual(original.started_at.?, parsed.started_at.?);
    try testing.expectEqual(original.finished_at.?, parsed.finished_at.?);
    try testing.expectEqual(original.exit_code.?, parsed.exit_code.?);
    try testing.expectEqual(original.timed_out, parsed.timed_out);
}

test "metaParse ignores unknown keys (forward-compat)" {
    var arena = std.heap.ArenaAllocator.init(testing.allocator);
    defer arena.deinit();
    const a = arena.allocator();
    const text =
        \\run_id=fwd-compat
        \\command=/bin/true
        \\future_field=42
        \\nested_thing=hello world
        \\once=1
        \\
    ;
    const r = try metaParse(a, text);
    try testing.expectEqualStrings("fwd-compat", r.run_id);
    try testing.expectEqualStrings("/bin/true", r.command);
    try testing.expect(r.once);
}

test "metaParse handles values containing equals signs" {
    // Cron commands frequently include env-var assignments like
    // FOO=bar before the command. Split-on-first-= must preserve those.
    var arena = std.heap.ArenaAllocator.init(testing.allocator);
    defer arena.deinit();
    const a = arena.allocator();
    const text =
        \\run_id=env-cmd
        \\command=PATH=/usr/local/bin /bin/echo hi
        \\
    ;
    const r = try metaParse(a, text);
    try testing.expectEqualStrings("PATH=/usr/local/bin /bin/echo hi", r.command);
}

