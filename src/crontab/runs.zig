test "metaSerialize omits unset optional fields" {
    var arena = std.heap.ArenaAllocator.init(testing.allocator);
    defer arena.deinit();
    const a = arena.allocator();
    const r = RunRecord{ .run_id = "minimal", .command = "/bin/true" };
    const bytes = try metaSerialize(a, r);
    try testing.expect(std.mem.indexOf(u8, bytes, "source_id") == null);
    try testing.expect(std.mem.indexOf(u8, bytes, "target_label") == null);
    try testing.expect(std.mem.indexOf(u8, bytes, "scheduled_for") == null);
    try testing.expect(std.mem.indexOf(u8, bytes, "started_at") == null);
    try testing.expect(std.mem.indexOf(u8, bytes, "finished_at") == null);
    try testing.expect(std.mem.indexOf(u8, bytes, "exit_code") == null);
    // once and timed_out are always emitted (bool defaults are recorded)
    try testing.expect(std.mem.indexOf(u8, bytes, "once=0") != null);
    try testing.expect(std.mem.indexOf(u8, bytes, "timed_out=0") != null);
}

test "metaRead returns null for nonexistent run_id" {
    var arena = std.heap.ArenaAllocator.init(testing.allocator);
    defer arena.deinit();
    const a = arena.allocator();
    const r = try metaRead(a, "definitely-does-not-exist-xyz-12345");
